import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {buildTextDwellContract} from '../runner/staged/dwell-browse.ts';
const dir='data/evidence/plans/stable-scripts-20261101/';
const cfg=JSON.parse(await fs.readFile(dir+'ai-batch-dwell-config.json','utf8'));
const frameJsonPath=path.resolve('evidence/staged-2026-11-02T00-19-22-514Z/59fd5523-153a-4811-812d-f61d1dc3fdd7.json');
const frame=JSON.parse(await fs.readFile(frameJsonPath,'utf8'));
const hash=(b:Buffer)=>createHash('sha256').update(b).digest('hex');
const rawPath=frame.path.replace(/\.png$/,'.ocr.json');
const old=cfg.dwellBrowse.contracts.find((c:any)=>c.sourceRunIds.length===1&&c.sourceRunIds[0]===134);
const next=await buildTextDwellContract(old,{path:frame.path,sha256:hash(await fs.readFile(frame.path)),ocrPath:frameJsonPath,ocrSha256:hash(await fs.readFile(frameJsonPath)),frameId:frame.id,rawPath,rawSha256:hash(await fs.readFile(rawPath))});
cfg.dwellBrowse.contracts=cfg.dwellBrowse.contracts.map((c:any)=>c.version===old.version?next:c);
cfg.aiTaskRecovery=false;
cfg.planFile=dir+'ai-ip-text-v2-plan.json';
cfg.taskPolicy='本轮验证已修复的IP周边浏览脚本：正常入口完整收集、精确当前任务及说明绑定，读到浏览5秒得奖励后本地有界等待并复查真实完成；任务内不用AI，不点击地址/商品，不补旧账。正确资产页两新帧稳定正增量才记账，结束息屏，不启调度。';
await fs.writeFile(dir+'ai-ip-text-v2-plan.json',JSON.stringify({items:[{...next.task,decision:'do',initialExecutions:1,reason:'用户确认修复已知5秒浏览缺失步骤，本轮验证新版本'}]},null,2)+'\n',{flag:'wx'});
await fs.writeFile(dir+'ai-ip-text-v2-config.json',JSON.stringify(cfg,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({config:dir+'ai-ip-text-v2-config.json',version:next.version,policy:next.textPolicy.version,dwellMs:next.dwellMs,aiTaskRecovery:cfg.aiTaskRecovery}));
